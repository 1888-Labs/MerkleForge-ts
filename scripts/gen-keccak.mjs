// Writes packages/merkle-hash/src/keccak-f1600.ts: Keccak-f[1600] unrolled
// over 50 local 32-bit words. Keeping the state in locals instead of a typed
// array is what makes it about 2x faster than a looped permutation in V8.
// Run `node scripts/gen-keccak.mjs` and then `pnpm format`.
import { writeFileSync } from 'node:fs'

// R[x][y]: rho rotation offset of lane (x, y).
const R = [
  [0, 36, 3, 41, 18],
  [1, 44, 10, 45, 2],
  [62, 6, 43, 15, 61],
  [28, 55, 25, 21, 56],
  [27, 20, 39, 8, 14],
]
const RC = [
  0x0000000000000001n,
  0x0000000000008082n,
  0x800000000000808an,
  0x8000000080008000n,
  0x000000000000808bn,
  0x0000000080000001n,
  0x8000000080008081n,
  0x8000000000008009n,
  0x000000000000008an,
  0x0000000000000088n,
  0x0000000080008009n,
  0x000000008000000an,
  0x000000008000808bn,
  0x800000000000008bn,
  0x8000000000008089n,
  0x8000000000008003n,
  0x8000000000008002n,
  0x8000000000000080n,
  0x000000000000800an,
  0x800000008000000an,
  0x8000000080008081n,
  0x8000000000008080n,
  0x0000000080000001n,
  0x8000000080008008n,
]

const lane = (x, y) => x + 5 * y
// 64-bit left rotation of (low, high) by n, as [low, high] expressions.
function rotl(l, h, n) {
  if (n === 0) return [l, h]
  if (n === 32) return [h, l]
  if (n < 32)
    return [`(${l} << ${n}) | (${h} >>> ${32 - n})`, `(${h} << ${n}) | (${l} >>> ${32 - n})`]
  const m = n - 32
  return [`(${h} << ${m}) | (${l} >>> ${32 - m})`, `(${l} << ${m}) | (${h} >>> ${32 - m})`]
}

const words = (c) => [BigInt.asIntN(32, c & 0xffffffffn), BigInt.asIntN(32, c >> 32n)].map(Number)
const vars = Array.from({ length: 25 }, (_, i) => [`a${i}l`, `a${i}h`]).flat()
const o = []
o.push('// Generated by scripts/gen-keccak.mjs. Do not edit by hand.')
o.push('')
o.push(`const RC_LO = Int32Array.of(${RC.map((c) => words(c)[0]).join(', ')})`)
o.push(`const RC_HI = Int32Array.of(${RC.map((c) => words(c)[1]).join(', ')})`)
o.push('')
o.push('/**')
o.push(' * Keccak-f[1600] in place on 50 32-bit words: lane `x + 5y` is words')
o.push(' * `2(x + 5y)` (low half) and `2(x + 5y) + 1` (high half), little-endian.')
o.push(' */')
o.push('export function keccakF1600(s: Int32Array): void {')
for (const [i, v] of vars.entries()) o.push(`  let ${v} = s[${i}] as number`)
o.push('  for (let round = 0; round < 24; round++) {')
for (let x = 0; x < 5; x++) {
  for (const half of ['l', 'h']) {
    o.push(
      `    const c${x}${half} = ${[0, 1, 2, 3, 4].map((y) => `a${lane(x, y)}${half}`).join(' ^ ')}`,
    )
  }
}
for (let x = 0; x < 5; x++) {
  const [rl, rh] = rotl(`c${(x + 1) % 5}l`, `c${(x + 1) % 5}h`, 1)
  o.push(`    const d${x}l = c${(x + 4) % 5}l ^ (${rl})`)
  o.push(`    const d${x}h = c${(x + 4) % 5}h ^ (${rh})`)
}
// Theta, then rho and pi: lane (x, y) moves to (y, 2x + 3y).
for (let x = 0; x < 5; x++) {
  for (let y = 0; y < 5; y++) {
    const i = lane(x, y)
    o.push(`    const t${i}l = a${i}l ^ d${x}l`)
    o.push(`    const t${i}h = a${i}h ^ d${x}h`)
    const [rl, rh] = rotl(`t${i}l`, `t${i}h`, R[x][y])
    const j = lane(y, (2 * x + 3 * y) % 5)
    o.push(`    const b${j}l = ${rl}`)
    o.push(`    const b${j}h = ${rh}`)
  }
}
// Chi.
for (let y = 0; y < 5; y++) {
  for (let x = 0; x < 5; x++) {
    const [i, j, k] = [lane(x, y), lane((x + 1) % 5, y), lane((x + 2) % 5, y)]
    for (const half of ['l', 'h'])
      o.push(`    a${i}${half} = b${i}${half} ^ (~b${j}${half} & b${k}${half})`)
  }
}
// Iota.
o.push('    a0l ^= RC_LO[round] as number')
o.push('    a0h ^= RC_HI[round] as number')
o.push('  }')
for (const [i, v] of vars.entries()) o.push(`  s[${i}] = ${v}`)
o.push('}')
o.push('')

writeFileSync(new URL('../packages/merkle-hash/src/keccak-f1600.ts', import.meta.url), o.join('\n'))
