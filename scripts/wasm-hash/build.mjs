// Compiles the Rust hash module to WebAssembly twice, with and without the
// SIMD proposal, and embeds both, base64-encoded, in
// packages/merkle-hash-wasm/src/wasm-module.ts. The package picks the SIMD
// build when the engine supports it (every current browser, Node, Deno, and
// Bun) and falls back to the scalar one. Embedding keeps the package a plain
// ES module that works everywhere with no bundler config. CI rebuilds it and
// fails if the committed copy differs.
//
//   node scripts/wasm-hash/build.mjs
import { execFileSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const dir = fileURLToPath(new URL('.', import.meta.url))
const linkArgs = '-C link-arg=--export=__heap_base -C link-arg=-zstack-size=65536'

function build(name, extraFlags) {
  execFileSync('cargo', ['build', '--release', '--locked', '--target-dir', `target/${name}`], {
    cwd: dir,
    stdio: 'inherit',
    env: { ...process.env, RUSTFLAGS: `${linkArgs} ${extraFlags}`.trim() },
  })
  return readFileSync(
    new URL(
      `target/${name}/wasm32-unknown-unknown/release/merkleforge_wasm_hash.wasm`,
      import.meta.url,
    ),
  )
}

const builds = {
  WASM_SCALAR: build('scalar', ''),
  WASM_SIMD: build('simd', '-C target-feature=+simd128'),
}

const constant = (name, wasm) => {
  const lines = wasm.toString('base64').match(/.{1,96}/g) ?? []
  return `/** ${name === 'WASM_SIMD' ? 'SIMD' : 'Scalar'} build (${wasm.length} bytes), base64-encoded. */
export const ${name} =
${lines.map((line, i) => `  '${line}'${i === lines.length - 1 ? '' : ' +'}`).join('\n')}
`
}

const source = `// Generated by scripts/wasm-hash/build.mjs from scripts/wasm-hash/src. Do not edit by hand.

${Object.entries(builds)
  .map(([name, wasm]) => constant(name, wasm))
  .join('\n')}`
writeFileSync(
  new URL('../../packages/merkle-hash-wasm/src/wasm-module.ts', import.meta.url),
  source,
)
for (const [name, wasm] of Object.entries(builds)) console.log(`${name}: ${wasm.length} bytes`)
